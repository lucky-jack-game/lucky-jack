// 進行の「間」の尺。**サーバーとクライアントの両方が読む唯一の場所。**
//
// shared/match.js は通信もタイマーも持たない純粋な状態機械なので、「いつ待つか」はそこには
// 書けない。かといって待ちの尺を各画面に置くと、server/match.js・PracticeMatch.jsx・
// PracticeTutorial.jsx の3箇所に同じ数字が散り、片方だけ直る——このリポジトリが繰り返し
// 踏んできた形そのもの（NEXT_ROUND_DELAY_MS は実際に「揃えること」という注意書き付きで
// 2箇所に書かれていた）。**尺だけを持つ薄いモジュールを1つ置いて、そこから配る。**
//
// ここに書いてよいのは「何ミリ秒待つか」だけ。誰が待つか・何を見せるかは呼び出し側の仕事。

// 決着を見せてから次の局を始めるまで。**決着と同じtickで次の局へ進めないこと**——
// 旧実装はそれをやって、その局を決めた一番大事な結果が一度も見えないまま次へ進んでいた。
export const NEXT_ROUND_DELAY_MS = 3000;

// ベットが1手も成立しない局で「ALL IN」を見せる尺。
// 拠出の上限は少ない方の残りライフなので、どちらかが残り1ライフになるとアンティ(1)が
// そのまま上限になり、積む余地が消える——実測でカジュアルの局の11.9%、そして
// **試合の28.6%がこの局で終わる**。ここを同じtickで畳むと、カードを選んだ瞬間に試合が
// 終わったようにしか見えない。
export const ALL_IN_HOLD_MS = 1200;

// 決着したポットが勝者へ渡るのを見せる尺。
// 開示に入った瞬間にポットを消していた版は、**賭けた灯りが誰の手に渡ったのかが一度も
// 見えず**、卓の上からは「賭けが成立したのか降りたのか」を読み取れなかった。
// 粒が滑る尺（three/Lights3D.jsx の SLIDE_MS = 460）＋読む間。
// **NEXT_ROUND_DELAY_MS より短く保つこと**——長くすると払い出しの途中で次の局が始まる。
export const POT_PAYOUT_MS = 1100;
