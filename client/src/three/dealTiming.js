// 配札の尺。**3D(three/Dispenser3D.jsx)とDOM(battle/MatchView.jsx)の両方が読む。**
//
// 卓の上を滑ってくるカードと、ドックに並ぶ手札の絵は別の技術で描かれているが、
// **同じ1回の配札を指している**——尺を2箇所に書くと、機械から出た札が着く前に手札が増えたり、
// 着いた後もしばらく手札が空だったりする（実際に前者になっていた）。
//
// このファイルは three.js を一切importしないので、DOM側からimportしても
// 3Dチャンク（gzip 380KB超）をメインバンドルへ引き込まない。**ここに描画の都合を書かないこと。**

// 1枚が排出口から受け手に着くまで。
export const DEAL_MS = 620;
// 2枚目以降をずらす幅。**同時に配らないこと**——重なると「何枚配ったか」が絵からも音からも消える。
export const DEAL_STAGGER_MS = 160;

// 局の頭に**何枚ずつ**配られるか。1局目だけは手札2枚を作るので2枚、以降は使った1枚の補充で1枚。
// 状態機械(shared/match.js)の draw() がやっていることと同じ——**枚数を勝手に決めないこと。**
export const dealtPerSide = (round) => (round <= 1 ? 2 : 1);

// 自分に配られるn枚目(0始まり)が着地する時刻（局の頭からのms）。
// 配る順は「自分→相手→自分→相手」なので、自分のn枚目は通し番号 2n 番目になる。
export const selfCardLandsAt = (n) => DEAL_MS + n * 2 * DEAL_STAGGER_MS;
